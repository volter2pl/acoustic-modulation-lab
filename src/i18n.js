export function getLanguage(search = "") {
  const requested = new URLSearchParams(search).get("lang");
  return SUPPORTED_LANGUAGES.includes(requested) ? requested : DEFAULT_LANGUAGE;
}

export function createI18n(language = DEFAULT_LANGUAGE) {
  const activeLanguage = SUPPORTED_LANGUAGES.includes(language)
    ? language
    : DEFAULT_LANGUAGE;
  const locale = activeLanguage === "pl" ? "pl-PL" : "en-US";

  const t = (key, variables = {}) => {
    const template =
      TRANSLATIONS[activeLanguage][key] ?? TRANSLATIONS[DEFAULT_LANGUAGE][key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) =>
      Object.hasOwn(variables, name) ? String(variables[name]) : `{${name}}`,
    );
  };

  const number = (value, digits = 1) =>
    new Intl.NumberFormat(locale, {
      minimumFractionDigits: digits,
      maximumFractionDigits: digits,
    }).format(value);

  return Object.freeze({ language: activeLanguage, locale, t, number });
}

export function applyDocumentTranslations(document, i18n, location = document.location) {
  document.documentElement.lang = i18n.language;
  document.title = i18n.t("meta.title");
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = i18n.t("meta.description");

  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = i18n.t(element.dataset.i18n);
  }
  for (const element of document.querySelectorAll("[data-i18n-aria-label]")) {
    element.setAttribute("aria-label", i18n.t(element.dataset.i18nAriaLabel));
  }

  const currentUrl = new URL(location.href);
  for (const link of document.querySelectorAll("[data-home-link]")) {
    link.href = `${currentUrl.pathname}${currentUrl.search}`;
  }
  for (const link of document.querySelectorAll("[data-language]")) {
    const targetLanguage = link.dataset.language;
    const targetUrl = new URL(currentUrl);
    if (targetLanguage === DEFAULT_LANGUAGE) targetUrl.searchParams.delete("lang");
    else targetUrl.searchParams.set("lang", targetLanguage);
    link.href = `${targetUrl.pathname}${targetUrl.search}${targetUrl.hash}`;
    const active = targetLanguage === i18n.language;
    link.classList.toggle("is-active", active);
    if (active) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  }
}
